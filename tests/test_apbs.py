def test_parse_takes_the_final_global_net_energy():
    """Earlier per-state totals are not solvation energies and must be ignored."""
    output = """
      Total electrostatic energy = 1.466301820312E+05 kJ/mol
      Total electrostatic energy = 2.123812697782E+05 kJ/mol
      Local net energy (PE 0) = -7.543418135448E+03 kJ/mol
      Global net ELEC energy = -7.543418135448E+03 kJ/mol
    """
    assert parse_apbs_energy(output) == pytest.approx(-7543.418135448)


def test_parse_reports_failure_with_context():
    with pytest.raises(ValueError, match="no 'Global net ELEC energy'"):
        parse_apbs_energy("APBS aborted: could not allocate grid")


def test_kj_to_kcal_conversion_constant():
    assert KJ_PER_KCAL == pytest.approx(4.184)
    assert -7543.42 / KJ_PER_KCAL == pytest.approx(-1802.92, abs=0.01)


