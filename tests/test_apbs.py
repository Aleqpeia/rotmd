def test_input_contains_two_states_differing_only_in_solvent_dielectric(tmp_path):
    """ΔG_elec is meaningful only if everything but sdie cancels."""
    grid = grid_dimensions(*read_pqr_from(tmp_path))
    path = write_apbs_input(tmp_path / "apbs.in", "frame.pqr", grid, pdie=2.0, sdie=78.54)
    text = path.read_text()

    assert "elec name solv" in text
    assert "elec name ref" in text
    assert "sdie 78.54" in text          # solvated
    assert text.count("sdie 2.0") == 1   # reference collapses onto pdie
    assert text.count("pdie 2.0") == 2   # identical solute dielectric in both
    assert "print elecEnergy solv - ref end" in text
    # Both blocks must share one grid, or the difference is a grid artefact.
    assert text.count(f"dime {grid['dime'][0]}") == 2


def read_pqr_from(tmp_path):
    path = tmp_path / "frame.pqr"
    path.write_text(PQR_SAMPLE)
    return read_pqr(path)


def test_potential_map_is_requested_only_when_asked(tmp_path):
    grid = grid_dimensions(*read_pqr_from(tmp_path))
    plain = write_apbs_input(tmp_path / "a.in", "f.pqr", grid).read_text()
    withdx = write_apbs_input(tmp_path / "b.in", "f.pqr", grid, potential_dx="pot").read_text()

    assert "write pot dx" not in plain
    assert withdx.count("write pot dx pot") == 1   # solvated state only


def test_ionic_strength_is_written_into_both_states(tmp_path):
    grid = grid_dimensions(*read_pqr_from(tmp_path))
    text = write_apbs_input(tmp_path / "a.in", "f.pqr", grid, ionic_strength=0.15).read_text()
    assert text.count("ion charge 1 conc 0.15") == 2


