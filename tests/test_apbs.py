def test_find_tool_locates_a_script_beside_the_interpreter(tmp_path, monkeypatch):
    """pip console scripts sit next to python and are often not on PATH."""
    fake_bin = tmp_path / "bin"
    fake_bin.mkdir()
    (fake_bin / "made_up_tool").write_text("#!/bin/sh\n")
    monkeypatch.setattr(sys, "executable", str(fake_bin / "python"))
    assert find_tool("made_up_tool") == str(fake_bin / "made_up_tool")


def test_find_tool_error_names_how_to_install():
    with pytest.raises(FileNotFoundError, match="micromamba install"):
        find_tool("definitely_not_a_real_binary_xyz")


