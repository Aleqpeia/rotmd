def test_sampling_spans_the_window_and_starts_at_t0():
    idx = sample_frame_indices(n_frames=1000, start=300, n_samples=10)
    assert idx.min() == 300
    assert idx.max() == 999
    assert len(idx) == 10
    assert np.all(np.diff(idx) > 0)


def test_sampling_is_deterministic():
    a = sample_frame_indices(1000, 0, 25)
    b = sample_frame_indices(1000, 0, 25)
    np.testing.assert_array_equal(a, b)


def test_sampling_cannot_exceed_available_frames():
    idx = sample_frame_indices(n_frames=10, start=5, n_samples=100)
    assert len(idx) <= 5
    assert idx.max() <= 9


def test_sampling_rejects_a_window_past_the_end():
    with pytest.raises(ValueError, match="beyond the"):
        sample_frame_indices(n_frames=10, start=10, n_samples=5)


