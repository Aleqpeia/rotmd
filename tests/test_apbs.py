"""T5c: Poisson-Boltzmann electrostatics.

The pure functions (grid sizing, input generation, output parsing) run
everywhere. The end-to-end calculation is marked ``integration`` and skips
unless both external binaries are present.
"""

from __future__ import annotations

import shutil
import sys
from pathlib import Path

import numpy as np
import pytest

from rotmd.analysis.apbs import (
    KJ_PER_KCAL,
    find_tool,
    grid_dimensions,
    parse_apbs_energy,
    read_pqr,
    sample_frame_indices,
    write_apbs_input,
)

_VALID_DIME = (33, 49, 65, 81, 97, 113, 129, 161, 193, 225, 257)

PQR_SAMPLE = """\
REMARK   1 generated by pdb2pqr
ATOM      1  N   MET A   1      10.000  10.000  10.000 -0.3000 1.8240
ATOM      2  CA  MET A   1      12.000  10.000  10.000  0.2100 1.9080
ATOM      3  C   MET A   1      10.000  14.000  10.000  0.5100 1.9080
ATOM      4  O   MET A   1      10.000  10.000  16.000 -0.5100 1.6612
TER
END
"""


def _apbs_tools_available() -> bool:
    have_apbs = shutil.which("apbs") is not None
    bindir = Path(sys.executable).parent
    have_pqr = shutil.which("pdb2pqr30") is not None or (bindir / "pdb2pqr30").is_file()
    return bool(have_apbs and have_pqr)


needs_tools = pytest.mark.skipif(
    not _apbs_tools_available(), reason="apbs and/or pdb2pqr30 not installed"
)


