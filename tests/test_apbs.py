def test_grid_dime_values_are_legal_for_apbs_multigrid():
    """APBS requires dime = c*2^(l+1)+1; an arbitrary value aborts the run."""
    coords, radii = np.array([[0.0, 0, 0], [30.0, 40.0, 50.0]]), np.array([1.5, 1.5])
    grid = grid_dimensions(coords, radii)
    for value in grid["dime"]:
        assert value in _VALID_DIME


def test_grid_boxes_follow_the_psize_heuristic():
    coords = np.array([[0.0, 0.0, 0.0], [10.0, 20.0, 30.0]])
    radii = np.array([1.0, 1.0])
    grid = grid_dimensions(coords, radii)

    extent = np.array([12.0, 22.0, 32.0])          # span + radii on both sides
    np.testing.assert_allclose(grid["extent"], extent)
    np.testing.assert_allclose(grid["cglen"], 1.7 * extent)
    np.testing.assert_allclose(grid["fglen"], np.minimum(20.0 + extent, 1.7 * extent))
    np.testing.assert_allclose(grid["centre"], [5.0, 10.0, 15.0])


def test_grid_is_capped_to_bound_memory():
    # A huge molecule must not request a 500^3 grid.
    coords = np.array([[0.0, 0, 0], [400.0, 400.0, 400.0]])
    grid = grid_dimensions(coords, np.array([1.0, 1.0]), max_dime=161)
    assert max(grid["dime"]) <= 161


def test_finer_spacing_requests_a_larger_grid():
    coords, radii = np.array([[0.0, 0, 0], [40.0, 40.0, 40.0]]), np.array([1.0, 1.0])
    coarse = grid_dimensions(coords, radii, fine_spacing=1.0)
    fine = grid_dimensions(coords, radii, fine_spacing=0.3)
    assert max(fine["dime"]) >= max(coarse["dime"])


