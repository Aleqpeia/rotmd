@needs_tools
@pytest.mark.integration
def test_pb_energy_on_a_real_frame(tmp_path):
    """A real PDB2PQR + APBS run must give a negative solvation free energy."""
    pytest.importorskip("MDAnalysis")
    data = Path.home() / ".cache/rotmd-testdata/n75k_prot.gro"
    if not data.exists():
        pytest.skip("real-data fixture not built")

    import MDAnalysis as mda

    from rotmd.analysis.apbs import run_single_frame

    u = mda.Universe(str(data))
    pdb = tmp_path / "frame.pdb"
    u.select_atoms("protein").write(str(pdb))

    result = run_single_frame(pdb, tmp_path / "work")
    # Polar solvation of a charged protein is strongly favourable; the sign is
    # the meaningful assertion, the magnitude is system-specific.
    assert result["dG_elec_kJ"] < 0
    assert result["dG_elec_kcal"] == pytest.approx(result["dG_elec_kJ"] / KJ_PER_KCAL)
    assert result["n_atoms"] > 1000
