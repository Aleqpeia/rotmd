def test_read_pqr_extracts_coordinates_and_radii(tmp_path):
    path = tmp_path / "x.pqr"
    path.write_text(PQR_SAMPLE)
    coords, radii = read_pqr(path)

    assert coords.shape == (4, 3)
    np.testing.assert_allclose(coords[0], [10.0, 10.0, 10.0])
    np.testing.assert_allclose(radii, [1.8240, 1.9080, 1.9080, 1.6612])


def test_read_pqr_rejects_a_file_with_no_atoms(tmp_path):
    path = tmp_path / "empty.pqr"
    path.write_text("REMARK nothing here\nEND\n")
    with pytest.raises(ValueError, match="no ATOM/HETATM"):
        read_pqr(path)


